"""HTTP API.

GET  /health               model and data status
POST /predict              ETA and late risk for one pickup task (plus a customer message if flagged)
GET  /at-risk?as_of=...    open tasks at a replay time whose risk is over the alert threshold

Interactive docs at /docs (generated by FastAPI from the request and response models below).
"""
from __future__ import annotations

import logging
import time
from datetime import datetime
from functools import lru_cache

import pandas as pd
from contextlib import asynccontextmanager

from fastapi import Depends, FastAPI, Query, Request
from pydantic import BaseModel, Field, model_validator

from . import notify
from .logs import log, setup_logging
from .models import ModelBundle
from .repository import PostgresRepository, Repository, as_python
from .settings import get_settings
from .store import request_features

logger = logging.getLogger("lade_eta.api")


@asynccontextmanager
async def lifespan(_app: FastAPI):
    setup_logging(get_settings().log_level)
    yield


app = FastAPI(title="LaDe pickup ETA and late-window alerts", version="1.0", lifespan=lifespan)


class PickupTask(BaseModel):
    order_id: int = 0
    courier_id: int
    region_id: int
    aoi_id: int
    aoi_type: int
    lng: float
    lat: float
    accept_time: datetime = Field(description="When the courier accepted the task (the prediction time)")
    time_window_start: datetime
    time_window_end: datetime
    accept_gps_lng: float | None = None
    accept_gps_lat: float | None = None
    courier_open_tasks: int | None = Field(None, description="Leave empty to look it up from the database")
    courier_tasks_today: int | None = None

    @model_validator(mode="after")
    def window_is_valid(self):
        if self.time_window_end <= self.time_window_start:
            raise ValueError("time_window_end must be after time_window_start")
        if self.accept_time >= self.time_window_end:
            raise ValueError("task accepted after its window closed: nothing to predict")
        return self


class Prediction(BaseModel):
    order_id: int
    eta_minutes: float
    estimated_pickup: datetime
    late_risk: float
    flagged: bool
    notification: str | None


class AtRiskItem(Prediction):
    courier_id: int
    region_id: int
    time_window_end: datetime


@lru_cache
def get_bundle() -> ModelBundle:
    return ModelBundle.load(get_settings().artifact_dir / "bundle.joblib")


@lru_cache
def get_repository() -> Repository:
    return PostgresRepository(get_settings().database_url)


@app.middleware("http")
async def access_log(request: Request, call_next):
    t0 = time.perf_counter()
    response = await call_next(request)
    log(logger, "request", path=request.url.path, status=response.status_code,
        ms=round((time.perf_counter() - t0) * 1000, 1))
    return response


def score(tasks: pd.DataFrame, bundle: ModelBundle, repo: Repository) -> list[dict]:
    """Shared by /predict and /at-risk: history as of each task's accept day, then both models."""
    rows = []
    for day, group in tasks.groupby(tasks["accept_time"].dt.normalize(), sort=False):
        feats = request_features(group, repo.snapshot(day))
        # One LightGBM thread per request: requests already run in parallel, so more threads only contend.
        eta = bundle.eta.predict(feats, num_threads=1).round(1)  # same value for eta_minutes and estimated_pickup
        risk = bundle.risk.predict(feats, num_threads=1)
        for i, rec in enumerate(feats.itertuples(index=False)):
            flagged = bool(risk[i] >= bundle.risk.threshold)
            msg = None
            if flagged:
                msg = notify.compose(rec.order_id, rec.time_window_start, rec.time_window_end,
                                     rec.accept_time, eta[i], risk[i]).message
            rows.append({
                "order_id": as_python(rec.order_id), "courier_id": as_python(rec.courier_id),
                "region_id": as_python(rec.region_id), "time_window_end": rec.time_window_end,
                "eta_minutes": float(eta[i]),
                "estimated_pickup": (rec.accept_time + pd.Timedelta(minutes=float(eta[i]))).round("s"),
                "late_risk": round(float(risk[i]), 4), "flagged": flagged, "notification": msg,
            })
    return rows


@app.get("/health")
def health(bundle: ModelBundle = Depends(get_bundle)) -> dict:
    return {"status": "ok", "city": bundle.metadata.get("city"), "alert_threshold": bundle.risk.threshold,
            "alert_budget": bundle.metadata.get("alert_budget")}


@app.post("/predict", response_model=Prediction)
def predict(task: PickupTask, bundle: ModelBundle = Depends(get_bundle), repo: Repository = Depends(get_repository)):
    row = task.model_dump()
    if row["courier_open_tasks"] is None or row["courier_tasks_today"] is None:
        open_n, today = repo.workload(task.courier_id, pd.Timestamp(task.accept_time))
        row["courier_open_tasks"] = open_n if row["courier_open_tasks"] is None else row["courier_open_tasks"]
        row["courier_tasks_today"] = today if row["courier_tasks_today"] is None else row["courier_tasks_today"]
    frame = pd.DataFrame([row])
    frame["accept_time"] = pd.to_datetime(frame["accept_time"])
    return score(frame, bundle, repo)[0]


@app.get("/at-risk", response_model=list[AtRiskItem])
def at_risk(
    as_of: datetime = Query(..., description="Replay time, e.g. 2022-10-12T10:00:00"),
    region_id: int | None = None,
    limit: int = Query(100, ge=1, le=1000),
    bundle: ModelBundle = Depends(get_bundle),
    repo: Repository = Depends(get_repository),
):
    tasks = repo.open_tasks(pd.Timestamp(as_of), region_id)
    if tasks.empty:
        return []
    tasks["accept_time"] = pd.to_datetime(tasks["accept_time"])
    scored = [r for r in score(tasks, bundle, repo) if r["flagged"]]
    scored.sort(key=lambda r: (r["time_window_end"], -r["late_risk"]))
    return scored[:limit]
