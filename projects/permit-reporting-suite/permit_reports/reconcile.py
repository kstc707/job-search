"""Reconcile every report against its independent SQL control totals.

For each report and each parameter set, four checks:
  1. baseline rows == SQL Command rows (moving the work into SQL did not change results)
  2. report grand totals == control totals
  3. totals read back from the PDF export == control totals
  4. totals read back from the Excel export == control totals
"""
from __future__ import annotations

import json
import tempfile
from dataclasses import dataclass, asdict
from pathlib import Path

from . import engine, exporters
from .params import ReportParams
from .reports import REPORTS

PARAM_SETS = [
    ReportParams.parse("2025-01-01", "2025-12-31"),
    ReportParams.parse("2023-01-01", "2025-12-31"),
    ReportParams.parse("2024-01-01", "2024-03-31"),
    ReportParams.parse("2024-07-01", "2024-07-31", "HBR"),
    ReportParams.parse("2025-01-01", "2025-06-30", "CEN", "Finaled"),
    ReportParams.parse("2023-06-01", "2024-05-31", "ALL", "Expired"),
    ReportParams.parse("2025-10-01", "2025-12-31", "ALL", "In Review"),
    ReportParams.parse("2024-02-29", "2024-02-29", "NTH"),            # leap day, single day
    ReportParams.parse("2025-12-01", "2025-12-31", "UNV", "Withdrawn"),  # fees only; no inspections
    ReportParams.parse("2022-01-01", "2022-12-31"),                    # before any data: all zeros
]


@dataclass
class Check:
    report: str
    params: str
    rows: int
    rows_match_baseline: bool
    totals_match_control: bool
    pdf_matches_control: bool
    xlsx_matches_control: bool
    control: dict

    @property
    def ok(self) -> bool:
        return (self.rows_match_baseline and self.totals_match_control
                and self.pdf_matches_control and self.xlsx_matches_control)


def _same(control: dict, other: dict) -> bool:
    return all(control[k] == other[k] for k in other)


def check(conn, report_id: str, params: ReportParams, out_dir: Path) -> Check:
    opt = engine.refresh(conn, report_id, params, "optimized")
    base = engine.refresh(conn, report_id, params, "baseline")
    ctl = engine.control_totals(conn, report_id, params)
    stem = f"{report_id}_{params.start}_{params.end}_{params.district}_{params.status}".replace(" ", "")
    pdf = exporters.to_pdf(opt, out_dir / f"{stem}.pdf")
    xlsx = exporters.to_xlsx(opt, out_dir / f"{stem}.xlsx")
    return Check(
        report_id, params.label(), len(opt.rows),
        rows_match_baseline=opt.rows == base.rows,
        totals_match_control=_same(ctl, opt.totals),
        pdf_matches_control=_same(ctl, exporters.read_pdf_totals(opt, pdf)),
        xlsx_matches_control=_same(ctl, exporters.read_xlsx_totals(opt, xlsx)),
        control={k: str(v) for k, v in ctl.items()},
    )


def run_all(conn, out_dir: Path | None = None, param_sets=PARAM_SETS) -> list[Check]:
    if out_dir is None:
        out_dir = Path(tempfile.mkdtemp(prefix="permit-exports-"))
    return [check(conn, rid, p, out_dir) for rid in REPORTS for p in param_sets]


def write_results(checks: list[Check], results_dir: Path) -> None:
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "reconciliation.json").write_text(
        json.dumps([asdict(c) | {"ok": c.ok} for c in checks], indent=2) + "\n")
    yes = lambda b: "yes" if b else "**NO**"
    lines = [
        "# Reconciliation results",
        "",
        f"{sum(c.ok for c in checks)} of {len(checks)} report/parameter checks passed "
        f"({len(REPORTS)} reports x {len(checks) // len(REPORTS)} parameter sets).",
        "",
        "Generated by `python -m permit_reports reconcile`.",
        "",
        "| Report | Parameters | Rows | Same as baseline | Totals = control | PDF = control | Excel = control |",
        "|---|---|---:|---|---|---|---|",
    ]
    for c in checks:
        lines.append(f"| {c.report} | {c.params} | {c.rows} | {yes(c.rows_match_baseline)} | "
                     f"{yes(c.totals_match_control)} | {yes(c.pdf_matches_control)} | {yes(c.xlsx_matches_control)} |")
    (results_dir / "reconciliation.md").write_text("\n".join(lines) + "\n")
